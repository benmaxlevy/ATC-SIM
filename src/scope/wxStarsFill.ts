export function wxLevelHasHatch(level: 1 | 2 | 3 | 4 | 5 | 6): boolean {
  return level === 2 || level === 4 || level === 6;
}

/** Screen-space hatch. Same origin for every VIP so 2/4/6 marks line up. */
export function wxHatchBit(screenX: number, screenY: number): boolean {
  const col = ((Math.floor(screenX) % WX_HATCH_W) + WX_HATCH_W) % WX_HATCH_W;
  const row = ((Math.floor(screenY) % WX_HATCH_H) + WX_HATCH_H) % WX_HATCH_H;
  return (WX_HATCH_ROWS[row]?.[col] ?? "0") === "1";
}
